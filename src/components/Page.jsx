import Head from "next/head";
import { Form } from "@/components/Form";
import { useEffect } from "react";
import { useDispatch } from "react-redux";
import { useRouter } from "next/router";
import { useInfo } from "@/redux/selectors";
import { setInfo } from "@/redux/slices";

export const Page = ({
  formDataLoader = () => {},
  children,
  prevParam,
  currentParam,
  nextRoute,
}) => {
  const router = useRouter();
  const dispatch = useDispatch();
  const info = useInfo();

  const onSubmit = async (event) => {
    const data = await formDataLoader(event);
    dispatch(setInfo({ [currentParam]: data[currentParam] }));
  };

  useEffect(() => {
    if (info[currentParam]) {
      router.push(nextRoute);
    }
    if (!info[prevParam]) {
      if (prevParam === "email") {
        router.replace(`/`);
        return;
      }
      router.replace(`/${prevParam}`);
    }
  }, [info]);

  return (
    <>
      <Head>
        <title>Create Next App</title>
        <meta name="description" content="Generated by create next app" />
        <meta name="viewport" content="width=device-width, initial-scale=1" />
        <link rel="icon" href="/favicon.ico" />
      </Head>
      <div>
        <Form onSubmit={onSubmit} prevParam={prevParam}>
          {children}
        </Form>
      </div>
    </>
  );
};
