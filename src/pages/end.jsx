export const getStaticProps = () => {
  return { props: { clientID: process.env.CLIENT_ID } };
};

const ThisForm = styled(StyledForm)`
  text-align: center;
  padding-top: 70px;
  & h1 {
    font-size: 50px;
  }
  & p {
    margin-top: 80px;
    text-align: justify;
  }
`;

export default function Home() {
  const router = useRouter();
  const dispatch = useDispatch();
  const loader = useLoader();
  const info = useInfo();

  useEffect(() => {
    (async () => {
      dispatch(enableLoader());
      if (
        !info.email ||
        !info.gender ||
        !info.age ||
        !info.jobe_status ||
        !info.family_income ||
        !info.education_level ||
        !info.eating_habits ||
        !info.food1 ||
        !info.food2 ||
        !info.food3 ||
        !info.food4 ||
        !info.info_source ||
        !info.choise_paramiters
      ) {
        console.log("No info");
        router.replace("/");
        return;
      }
      try {
        const food = {
          ...JSON.parse(info.food1),
          ...JSON.parse(info.food2),
          ...JSON.parse(info.food3),
          ...JSON.parse(info.food4),
        };
        console.log(food);
        const data = await createFood({
          google_id: info.email,
          gender: info.gender,
          age: info.age,
          jobe_status: info.jobe_status,
          family_income: info.family_income,
          education_level: info.education_level,
          eating_habits: JSON.stringify(info.eating_habits),
          food: JSON.stringify(food),
          info_source: JSON.stringify(info.info_source),
          choise_paramiters: JSON.stringify(info.choise_paramiters),
        });
        console.log(data);

        setTimeout(() => {
          dispatch(resetInfo());
          router.replace("/");
        }, 3000);
      } catch (err) {
        console.log(err);
      }
      dispatch(disableLoader());
    })();
  }, [dispatch, info]);

  return (
    <>
      <Head>
        <title>Create Next App</title>
        <meta name="description" content="Generated by create next app" />
        <meta name="viewport" content="width=device-width, initial-scale=1" />
        <link rel="icon" href="/favicon.ico" />
      </Head>
      <div>
        {loader && <Loader />}
        <ThisForm>
          <div>
            <h1>
              Дякуємо за участь в опитуванні! Ваші відповіді є важливим внеском
              у дослідженні здорового харчування споживачів.
            </h1>
          </div>
        </ThisForm>
      </div>
    </>
  );
}

